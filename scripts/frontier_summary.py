"""Write the frontier summary for every model to docs/frontier-summary.{json,md}.

    python3 scripts/frontier_summary.py [results/campaign.sqlite]

Read-only on the store. The JSON is the hand-off object for the UI (one card
per model: verdict sentence + one row per capability); the markdown is the
same content for people.
"""
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

from cartographer.report.frontier import STATUS_ORDER, frontier_summaries  # noqa: E402
from cartographer.store.store import ResultsStore  # noqa: E402

db = sys.argv[1] if len(sys.argv) > 1 else "results/campaign.sqlite"
summaries = frontier_summaries(ResultsStore.open_read_only(db))
docs = pathlib.Path(__file__).resolve().parents[1] / "docs"
(docs / "frontier-summary.json").write_text(json.dumps([m.to_json_dict() for m in summaries], indent=1, default=str))

lines = ["# Frontier summary", "",
         "Generated by `scripts/frontier_summary.py` from the store. Statuses: BREAKS (a tested level fell to "
         "<= 30% pass), DEGRADES (<= 75%, or for single-rate rows a 95% CI entirely below 95%), HOLDS, "
         "NOT TESTED. Confidence: A strong, B moderate, C thin.", ""]
for m in summaries:
    lines += [f"## {m.name}", "", f"**{m.verdict}**", "",
              "| capability | status | conf. | result | cause |", "|---|---|---|---|---|"]
    for r in sorted(m.rows, key=lambda r: STATUS_ORDER[r.status]):
        cause = f"{r.cause} ({r.cause_share:.0%} of failures)" if r.cause else ""
        lines.append(f"| {r.label} | {r.status} | {r.confidence or ''} | {r.headline} | {cause} |")
    lines.append("")
(docs / "frontier-summary.md").write_text("\n".join(lines))
print(f"wrote docs/frontier-summary.json and .md for {len(summaries)} models")
