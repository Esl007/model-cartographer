"""Offline foil-classification report: turns the "71% of belief FAILs match
a foil" observation into a standing, re-runnable artifact.

Loads `results/campaign.sqlite` READ-ONLY, finds every post-witness-fix
belief FAIL for the model tiers of interest, regenerates each world from
its stored `(latent_params, task_seed, rendering_seed)`, computes the
foil profile (`cartographer.world.foils.foil_divergence`), and checks
whether the model's actual (normalized) response text matches one of the
diverging foils' surface strings. Prints one table per model, then an
overall summary.

Exact regeneration is only possible for records produced with the SAME
`cartographer.world.generate.generate` logic as HEAD -- i.e. runs started
strictly after the `313e3b2` generator-hardening commit (2026-09-17
17:20:02 UTC), which changed chain-actor exclusion/witness-set assignment.
Earlier belief runs (`camp-belief-nemotron-nano-001`,
`camp-belief-nemotron-super-002`) predate that commit and are skipped with
a warning rather than silently mis-attributed to the wrong world.

Zero network calls: read-only sqlite access plus pure-simulation world
regeneration. Main-guarded so importing this module has no side effects.
"""

from __future__ import annotations

import re
import string
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from cartographer.exec.evaluator import _apply_config, _default_base  # noqa: E402
from cartographer.render import build_name_map, render  # noqa: E402
from cartographer.store.schema import ExperimentRecord, Verdict  # noqa: E402
from cartographer.store.store import ResultsStore  # noqa: E402
from cartographer.world.foils import foil_divergence  # noqa: E402
from cartographer.world.generate import generate  # noqa: E402

DEFAULT_DB_PATH = Path(__file__).resolve().parent.parent / "results" / "campaign.sqlite"

# Belief runs known to be reconstructable exactly under the CURRENT
# generator (post `313e3b2`, 2026-09-17 17:20:02 UTC). Runs before that
# commit used a different chain-actor exclusion/witness-set assignment
# path and cannot be exactly regenerated by today's `generate()` -- see
# module docstring. Extend this list as new post-fix belief campaigns are
# recorded.
TARGET_RUN_IDS = [
    "camp-belief-nemotron-3-super-120b-a12b-001",
    "camp-belief-nemotron-3-ultra-550b-a55b-001",
    "camp-belief-nvidia-nemotron-3-nano-30b-a3b-001",
]

# Runs that exist in the store but predate the generator-hardening commit
# and therefore CANNOT be exactly regenerated -- listed explicitly so the
# report can warn about them instead of silently omitting them.
KNOWN_UNRECONSTRUCTABLE_RUN_IDS = [
    "camp-belief-nemotron-nano-001",
    "camp-belief-nemotron-super-002",
]

_ARTICLES = {"the", "a", "an"}


def _normalize(text: str) -> str:
    text = text.lower()
    text = text.translate(str.maketrans("", "", string.punctuation))
    tokens = [t for t in text.split() if t not in _ARTICLES]
    return " ".join(tokens)


def _regenerate_world_and_profile(record: ExperimentRecord):
    """Rebuild the exact `(World, NameMap, RenderedTask)` a record was
    generated from, purely from stored provenance -- no API calls."""
    query_kind = None
    if record.verifier_detail:
        m = re.search(r"kind=([a-z]+)", record.verifier_detail)
        if m:
            query_kind = m.group(1)
    if query_kind is None:
        query_kind = "belief"  # this script only targets belief FAILs anyway

    base = _default_base(query_kind)
    params = _apply_config(base, record.latent_params)
    world = generate(params, record.task_seed)
    name_map = build_name_map(world, record.rendering_seed)
    rendered = render(world, name_map, record.rendering_seed)
    profile = foil_divergence(world, name_map)
    return world, name_map, rendered, profile


def classify_fail(record: ExperimentRecord) -> tuple[str | None, bool]:
    """Returns (matched_trap_kind_or_None, prompt_reconstructed_exactly).

    `matched_trap_kind_or_None` is the name of the diverging foil whose
    surface string the model's (normalized) response contains, preferring
    the first match in `profile.trap_kinds`' sorted order for determinism
    when a response happens to match more than one foil's surface string
    (can happen when two foils coincide on the same wrong location).
    Returns `(None, reconstructed)` if the response matches no diverging
    foil (an unclassified FAIL -- may be a different failure mode
    entirely, e.g. hedging or a location never mentioned in the story).
    """
    world, name_map, rendered, profile = _regenerate_world_and_profile(record)
    reconstructed_exactly = rendered.prompt == record.prompt_text

    response_norm = _normalize(record.response_text or "")
    for trap_kind in profile.trap_kinds:
        foil_surface = profile.foils.get(trap_kind)
        if foil_surface is None:
            continue
        if _normalize(foil_surface) in response_norm:
            return trap_kind, reconstructed_exactly
    return None, reconstructed_exactly


def build_report(db_path: Path = DEFAULT_DB_PATH, run_ids: list[str] | None = None) -> dict:
    run_ids = run_ids if run_ids is not None else TARGET_RUN_IDS
    store = ResultsStore(db_path)
    try:
        per_model: dict[str, Counter] = defaultdict(Counter)
        per_model_totals: dict[str, int] = defaultdict(int)
        per_model_reconstructed: dict[str, int] = defaultdict(int)
        skipped_unreconstructable: list[str] = []

        for run_id in run_ids:
            records = store.by_run(run_id)
            fails = [r for r in records if r.verdict == Verdict.FAIL]
            for record in fails:
                model = record.model_name
                trap_kind, reconstructed = classify_fail(record)
                per_model_totals[model] += 1
                if reconstructed:
                    per_model_reconstructed[model] += 1
                label = trap_kind if trap_kind is not None else "UNCLASSIFIED"
                per_model[model][label] += 1

        for run_id in KNOWN_UNRECONSTRUCTABLE_RUN_IDS:
            if store.by_run(run_id):
                skipped_unreconstructable.append(run_id)
    finally:
        store.close()

    return {
        "per_model": dict(per_model),
        "per_model_totals": dict(per_model_totals),
        "per_model_reconstructed": dict(per_model_reconstructed),
        "skipped_unreconstructable": skipped_unreconstructable,
    }


def _model_short(model: str) -> str:
    return model.split("/")[-1]


def print_report(report: dict) -> None:
    per_model = report["per_model"]
    totals = report["per_model_totals"]
    reconstructed = report["per_model_reconstructed"]

    grand_total = 0
    grand_matched = 0

    for model in sorted(per_model):
        total = totals[model]
        recon = reconstructed[model]
        print(f"\n=== {_model_short(model)} ({total} belief FAILs, {recon}/{total} exactly reconstructed) ===")
        print(f"{'trap kind':<28} {'count':>6} {'% of FAILs':>12}")
        print("-" * 48)
        counter = per_model[model]
        matched = 0
        for label, count in counter.most_common():
            pct = 100.0 * count / total if total else 0.0
            print(f"{label:<28} {count:>6} {pct:>11.1f}%")
            if label != "UNCLASSIFIED":
                matched += count
        grand_total += total
        grand_matched += matched
        print(f"{'(any foil matched)':<28} {matched:>6} {100.0 * matched / total if total else 0.0:>11.1f}%")

    print("\n=== overall ===")
    if grand_total:
        print(
            f"{grand_matched}/{grand_total} belief FAILs "
            f"({100.0 * grand_matched / grand_total:.1f}%) matched a plausible-but-wrong foil answer"
        )
    else:
        print("no belief FAILs found for the configured run_ids")

    if report["skipped_unreconstructable"]:
        print(
            "\nNote: the following belief runs predate the generator-hardening "
            "commit (313e3b2, 2026-09-17 17:20:02 UTC) and cannot be exactly "
            "regenerated by the current generate() -- excluded from this report:"
        )
        for run_id in report["skipped_unreconstructable"]:
            print(f"  - {run_id}")


if __name__ == "__main__":
    report = build_report()
    print_report(report)
